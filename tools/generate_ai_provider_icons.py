"""Generate LVGL alpha-1bit provider icons from traceable source assets.

Sources:
- Devin Desktop installed application tile:
  D:/Program Files/Devin/resources/app/resources/win32/code_150x150.png
- Xiaomi MiMo installed application SVG:
  %APPDATA%/Xiaomi MiMo/runtime-res/releases/main/resources/assets/icon-nonmac-source.svg
- Claude mark from the CC0-licensed Simple Icons project:
  https://cdn.simpleicons.org/claude
- Existing project ChatGPT alpha icon, originally sourced for the current production UI.

The output is deterministic C data. It contains no downloaded source image.
"""

from __future__ import annotations

import io
import os
import re
import urllib.request
from pathlib import Path

import cairosvg
from PIL import Image, ImageChops


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware/components/app_ui/ai_provider_icons.inc"
SOURCES = {
    "devin": Path(r"D:/Program Files/Devin/resources/app/resources/win32/code_150x150.png"),
    "mimo": Path(os.environ["APPDATA"]) / "Xiaomi MiMo/runtime-res/releases/main/resources/assets/icon-nonmac-source.svg",
    "claude": "https://cdn.simpleicons.org/claude",
}


def load_existing_chatgpt() -> Image.Image:
    source = ROOT / "firmware/components/app_ui/chatgpt_logo_alpha.inc"
    values = [int(token, 16) for token in re.findall(r"0x([0-9a-fA-F]{2})", source.read_text(encoding="utf-8"))]
    image = Image.new("RGBA", (24, 24), (0, 0, 0, 0))
    pixels = image.load()
    stride = 3
    for y in range(24):
        for x in range(24):
            if values[y * stride + x // 8] & (1 << (7 - x % 8)):
                pixels[x, y] = (0, 0, 0, 255)
    return image


def load_image(source: Path | str) -> Image.Image:
    if isinstance(source, Path):
        data = source.read_bytes()
        suffix = source.suffix.lower()
    else:
        request = urllib.request.Request(source, headers={"User-Agent": "deskwong-icon-generator/1.0"})
        with urllib.request.urlopen(request, timeout=30) as response:
            data = response.read()
        suffix = ".svg"
    if suffix == ".svg" or data.lstrip().startswith(b"<svg"):
        data = cairosvg.svg2png(bytestring=data, output_width=512, output_height=512)
    return Image.open(io.BytesIO(data)).convert("RGBA")


def foreground_mask(image: Image.Image) -> Image.Image:
    alpha = image.getchannel("A")
    if alpha.getextrema()[0] < 250:
        return alpha.point(lambda value: 255 if value >= 64 else 0)
    rgb = image.convert("RGB")
    bg = Image.new("RGB", rgb.size, rgb.getpixel((0, 0)))
    diff = ImageChops.difference(rgb, bg).convert("L")
    return diff.point(lambda value: 255 if value >= 24 else 0)


def render_bits(image: Image.Image, size: int) -> bytes:
    mask = foreground_mask(image)
    bbox = mask.getbbox()
    if not bbox:
        raise ValueError("source has no visible foreground")
    mask = mask.crop(bbox)
    inner = max(1, size - (4 if size >= 24 else 2))
    mask.thumbnail((inner, inner), Image.Resampling.LANCZOS)
    canvas = Image.new("L", (size, size), 0)
    canvas.paste(mask, ((size - mask.width) // 2, (size - mask.height) // 2))
    canvas = canvas.point(lambda value: 255 if value >= 112 else 0)
    packed = bytearray()
    for y in range(size):
        for start in range(0, size, 8):
            value = 0
            for bit in range(8):
                x = start + bit
                if x < size and canvas.getpixel((x, y)):
                    value |= 1 << (7 - bit)
            packed.append(value)
    return bytes(packed)


def main() -> None:
    lines = ["/* Generated by tools/generate_ai_provider_icons.py; see script for sources. */"]
    sources = {"chatgpt": load_existing_chatgpt(), **SOURCES}
    for name, source in sources.items():
        image = source if isinstance(source, Image.Image) else load_image(source)
        for size in (16, 24, 32):
            data = render_bits(image, size)
            lines.append(f"static const uint8_t s_{name}_{size}_alpha[] = {{")
            for offset in range(0, len(data), 12):
                chunk = data[offset : offset + 12]
                lines.append("    " + ", ".join(f"0x{value:02X}" for value in chunk) + ",")
            lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
